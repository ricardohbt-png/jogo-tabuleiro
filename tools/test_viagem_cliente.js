// Contrato cliente da escolha estrada/caravana e respostas de viagem.
const fs = require('fs');
const path = require('path');
let PASS = 0, FAIL = 0;
const check = (n, ok) => { if (ok) { PASS++; console.log('  ✅ ' + n); } else { FAIL++; console.log('  ❌ ' + n); } };
let sock = null, out = [];
global.WebSocket = class { constructor(){ this.readyState=1; sock=this; } send(data){ out.push(JSON.parse(data)); } close(){} };
global.window = {};
global.localStorage = {getItem:()=>null,setItem:()=>{},removeItem:()=>{}};
global.location = {search:'',protocol:'http:',host:'test'};
global.setTimeout = () => 0; global.clearTimeout = () => {};
const GS = eval(fs.readFileSync(path.join(__dirname,'..','src','gameState.js'),'utf8')+'; GS');
GS.connect('ws://test','Ana','create');
GS.worldTravel('vila_riacho','road');
GS.worldTravel('vila_corvin','caravan');
GS.respondCaravanSponsorship('req-1',true);
GS.respondCaravanSponsorship('req-2',false);
GS.worldAdventureEncounterChoice('continue');
check('envia modo de viagem como intenção', out[0]?.type==='world_travel' && out[0]?.mode==='road');
check('envia caravana sem valores calculados no cliente', out[1]?.type==='world_travel' && out[1]?.mode==='caravan' && !('fare' in out[1]));
check('responde patrocínio com id e aceite', out[2]?.type==='caravan_sponsorship_response' && out[2]?.request_id==='req-1' && out[2]?.accept===true);
check('responde recusa sem criar dívida', out[3]?.type==='caravan_sponsorship_response' && out[3]?.accept===false);
check('envia escolha de continuação da masmorra', out[4]?.type==='world_adventure_encounter_choice' && out[4]?.choice==='continue');
let request=null, choice=null, started=null, failed=null, closed=null;
GS.on('caravanSponsorshipRequest', m=>request=m);
GS.on('caravanSponsorshipStarted', m=>started=m);
GS.on('caravanSponsorshipFailed', m=>failed=m);
GS.on('caravanSponsorshipClosed', m=>closed=m);
GS.on('worldAdventureEncounterChoice', m=>choice=m);
sock.onmessage({data:JSON.stringify({type:'caravan_sponsorship_request',request_id:'req-3',passenger:'Beto',fare:12})});
sock.onmessage({data:JSON.stringify({type:'caravan_sponsorship_started',destination:'vila_riacho'})});
sock.onmessage({data:JSON.stringify({type:'caravan_sponsorship_failed',reason:'declined'})});
sock.onmessage({data:JSON.stringify({type:'caravan_sponsorship_closed',request_id:'req-3'})});
sock.onmessage({data:JSON.stringify({type:'world_adventure_encounter_choice',adventure_id:'ruinas'})});
check('repassa pedido do mercador ao renderer', request?.request_id==='req-3');
check('repassa espera de cobertura ao renderer', started?.destination==='vila_riacho');
check('repassa falha de cobertura ao renderer', failed?.reason==='declined');
check('repassa fechamento do prompt ao renderer', closed?.request_id==='req-3');
check('repassa decisão pós-emboscada ao renderer', choice?.adventure_id==='ruinas');
console.log(`\n${PASS} ok, ${FAIL} falha(s)`);
process.exit(FAIL ? 1 : 0);
